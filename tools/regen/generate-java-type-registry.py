#!/usr/bin/env python3
"""Generate the opt-in Java.type string-literal registries.

`Java.type("net.minecraft.util.Mth")` can be typed WITHOUT generics or
imports: ambient declares an empty `interface JavaTypeRegistry {}` merge
target plus an overload

    type<K extends keyof JavaTypeRegistry>(className: K): JavaTypeRegistry[K];

and these generated files populate the registry via declaration merging when
a consumer opts in through tsconfig/jsconfig "types". This also works for
plain-JS users via the editor language service (string autocomplete + typed
result, no JSDoc needed).

Two variants (each `import()` type pulls its module into the program, so
registry size = compile cost; measured on this tree):

  registry-lb/    net.ccbluex.* classes (~2.6k entries, ~+1s tsc) — the
                  recommended default for scripts reaching into LB internals.
  registry-full/  every generated class (~49k entries; ~+30s tsc) — fine for
                  editor/language-service use, heavy for batch compiles.

Only `export class` files get entries (interfaces have no value to
`typeof`; at runtime Java.type on an interface is mainly a Java.extend
input, which stays on the generic overload). Runs AFTER sanitize-invalid-dts
so deleted/repaired files never get entries.

Usage: generate-java-type-registry.py [path/to/typings]
"""
import os
import pathlib
import re
import sys

PKG = (pathlib.Path(sys.argv[1]) if len(sys.argv) > 1
       else pathlib.Path(__file__).resolve().parents[2] / "typings")
TYPES = PKG / "types"

EXPORT_RE = re.compile(r"^export (?:abstract )?(class|interface) ([^\s<{]+)", re.M)

HEADER = """// GENERATED by tools/regen/generate-java-type-registry.py — do not edit.
//
// Opt-in Java.type string-literal registry ({variant}): merge these entries
// into the ambient JavaTypeRegistry so
//     const Mth = Java.type("net.minecraft.util.Mth");
// is fully typed from the string alone. Enable via tsconfig/jsconfig:
//     "types": ["@wunk/lb-script-api-types/ambient",
//               "@wunk/lb-script-api-types/{name}"]
// Cost: every entry's module joins the program on use of the registry —
// {cost}.
declare global {{
interface JavaTypeRegistry {{
"""


def collect():
    entries = []
    for dp, _, fs in os.walk(TYPES):
        for f in fs:
            if not f.endswith(".d.ts"):
                continue
            p = pathlib.Path(dp) / f
            name = f[:-5]
            try:
                head = p.read_text(encoding="utf-8")[:4096]
            except Exception:
                continue
            m = EXPORT_RE.search(head)
            if not m or m.group(2) != name or m.group(1) != "class":
                continue
            rel = p.relative_to(PKG).as_posix()[:-5]      # types/...
            binary = p.relative_to(TYPES).as_posix()[:-5].replace("/", ".")
            entries.append((binary, rel, name))
    entries.sort()
    return entries


def write(variant_dir: pathlib.Path, entries, variant, name, cost):
    variant_dir.mkdir(parents=True, exist_ok=True)
    with open(variant_dir / "index.d.ts", "w", encoding="utf-8") as out:
        out.write(HEADER.format(variant=variant, name=name, cost=cost))
        for binary, rel, exp in entries:
            out.write(f'    "{binary}": typeof import("../{rel}").{exp};\n')
        out.write("}\n}\nexport {};\n")


def main():
    entries = collect()
    lb = [e for e in entries if e[0].startswith("net.ccbluex.")]
    write(PKG / "registry-lb", lb, "LiquidBounce classes", "registry-lb",
          "small (~1s)")
    write(PKG / "registry-full", entries, "every generated class",
          "registry-full", "LARGE (tens of seconds in batch tsc; intended "
          "for editor use)")
    print(f"java-type-registry: registry-lb {len(lb)} entries, "
          f"registry-full {len(entries)} entries")


if __name__ == "__main__":
    main()
